def make_entry(translations: dict) -> dict:
    localizations = {}
    for lang in LANGS:
        localizations[lang] = {
            "stringUnit": {
                "state": "translated",
                "value": translations[lang],
            }
        }
    return {
        "extractionState": "manual",
        "localizations": localizations,
    }


def main():
    path = Path(__file__).resolve().parents[2] / "budgetmeter.ios/Resources/UI.xcstrings"
    with open(path, encoding="utf-8") as f:
        data = json.load(f)

    added = 0
    skipped = 0
    for key, translations in NEW_STRINGS.items():
        if key in data["strings"]:
            skipped += 1
            continue
        data["strings"][key] = make_entry(translations)
        added += 1

    data["strings"] = dict(sorted(data["strings"].items()))
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Added {added} keys, skipped {skipped} existing keys")


if __name__ == "__main__":
    main()
